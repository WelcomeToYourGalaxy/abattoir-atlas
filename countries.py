_BY_ISO3 = {a3: (a2, name) for a3, a2, name in ISO3166}
_BY_ISO2 = {a2: a3 for a3, a2, _ in ISO3166}

_unresolved: dict[str, int] = {}


def _norm(s: str) -> str:
    s = unicodedata.normalize("NFKD", s)
    s = "".join(c for c in s if not unicodedata.combining(c)).lower()
    s = re.sub(r"\(.*?\)", " ", s)          # "United Kingdom (Northern Ireland)"
    s = re.sub(r"[^a-z0-9]+", " ", s).strip()
    s = re.sub(r"^the\s+", "", s)
    return s


def to_iso3(value: str | None) -> str | None:
    """ISO 3166-1 alpha-3 for a country name, code, or Chinese name.

    Returns None when the value cannot be resolved, and records it so
    `unresolved()` can report what a source is publishing that this table does
    not know. Nothing is guessed: an unrecognised name produces no code rather
    than a plausible-looking one.
    """
    if not value:
        return None
    raw = str(value).strip()
    if not raw:
        return None

    if raw in _ZH_TO_ISO3:                       # CIFER
        return _ZH_TO_ISO3[raw]

    up = raw.upper()
    if len(up) == 3 and up in _BY_ISO3:
        return up
    if len(up) == 2 and up in _BY_ISO2:
        return _BY_ISO2[up]

    key = _norm(raw)
    hit = _NAME_TO_ISO3.get(key)
    if hit:
        return hit

    # "Spain / España", "Myanmar/Burma", "Congo, Republic of the"
    for part in re.split(r"[/|]| and | e | y ", raw):
        k = _norm(part)
        if k and k in _NAME_TO_ISO3:
            return _NAME_TO_ISO3[k]

    _unresolved[raw] = _unresolved.get(raw, 0) + 1
    return None


def to_iso2(iso3: str | None) -> str | None:
    """Alpha-2, which is what Nominatim's countrycodes filter takes."""
    if not iso3:
        return None
    entry = _BY_ISO3.get(iso3.upper())
    return entry[0] if entry else None


def english_name(iso3: str | None) -> str | None:
    """Plain English name, for the geocoder query and the map legend."""
    if not iso3:
        return None
    entry = _BY_ISO3.get(iso3.upper())
    return entry[1] if entry else None


def unresolved() -> dict[str, int]:
    """Country strings seen this run that the table could not place."""
    return dict(sorted(_unresolved.items(), key=lambda kv: -kv[1]))
