"""
Country resolution.

Every source in this atlas names countries differently: TRACES prints English
names ("Türkiye", "United Kingdom (Northern Ireland)", "Myanmar/Burma"), CIFER
prints them in Chinese, FSIS prints nothing because it is one country. The rest
of the pipeline needs one ISO 3166-1 alpha-3 code per record, because dedup
blocks on it and the geocoder filters on it.

The rule that used to stand in for this module was `name.upper()[:3]`. It put
the United Kingdom, the United States and the United Arab Emirates in one
bucket called UNI, Spain in one called SPA, and turned every geocoder query
into a string ending in a three-letter fragment no gazetteer recognises. The
table below exists so that never happens again: a name either resolves to a
real code or it resolves to nothing and is reported.
"""

